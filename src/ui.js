export function el (tag, props = {}, ...kids) {
  const node = document.createElement(tag)
  for (const [k, v] of Object.entries(props)) {
    if (k === 'class') node.className = v
    else if (k === 'html') node.innerHTML = v
    else if (k === 'style') Object.assign(node.style, v)
    else if (k.startsWith('on') && typeof v === 'function') node.addEventListener(k.slice(2), v)
    else if (v !== null && v !== undefined && v !== false) node.setAttribute(k, v === true ? '' : v)
  }
  for (const kid of kids.flat()) {
    if (kid == null) continue
    node.append(kid.nodeType ? kid : document.createTextNode(String(kid)))
  }
  return node
}

/**
 * Stor ikonknap. x/y er i logiske 960x600-koordinater og bliver til procent,
 * saa knappen foelger med naar scenen skaleres.
 */
export function iconButton (opts) {
  const b = el('button', {
    class: 'btn ' + (opts.class || '') + (opts.x != null ? ' pos' : ''),
    type: 'button',
    html: opts.html || ICONS[opts.icon] || '',
    'aria-label': opts.label || opts.icon || 'knap'
  })
  if (opts.x != null) {
    b.style.left = (opts.x / 960) * 100 + '%'
    b.style.top = (opts.y / 600) * 100 + '%'
  }
  if (opts.title) b.title = opts.title
  if (opts.onClick) b.addEventListener('click', opts.onClick)
  return b
}

export function starRow (count, total = 3, size = 46) {
  const wrap = el('div', { style: { display: 'flex', gap: '6px' } })
  for (let i = 0; i < total; i++) {
    const s = el('span', {
      class: 'star',
      html: ICONS.star,
      style: {
        width: size + 'px',
        height: size + 'px',
        display: 'block',
        color: i < count ? '#ffc300' : 'rgba(0,0,0,.18)'
      }
    })
    s.querySelector('svg').style.width = '100%'
    s.querySelector('svg').style.height = '100%'
    wrap.append(s)
  }
  return wrap
}

/** Knap der skal holdes nede (voksen-laas paa "start forfra"). */
export function holdButton (opts) {
  const b = iconButton(opts)
  const ring = el('div', { class: 'hold-ring' })
  b.append(ring)
  let raf = 0
  let start = 0
  const duration = (opts.seconds || 3) * 1000

  const tick = () => {
    const t = Math.min(1, (performance.now() - start) / duration)
    ring.style.clipPath = `inset(0 ${100 - t * 100}% 0 0)`
    if (t >= 1) { stop(); opts.onHold?.() } else raf = requestAnimationFrame(tick)
  }
  const begin = ev => {
    ev.preventDefault()
    opts.onStart?.()
    start = performance.now()
    cancelAnimationFrame(raf)
    raf = requestAnimationFrame(tick)
  }
  const stop = () => {
    cancelAnimationFrame(raf)
    ring.style.clipPath = 'inset(0 100% 0 0)'
  }
  b.addEventListener('pointerdown', begin)
  b.addEventListener('pointerup', stop)
  b.addEventListener('pointercancel', stop)
  b.addEventListener('pointerleave', stop)
  return b
}
